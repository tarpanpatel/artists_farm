function translateEntry(key, enVal) {
  if (fullTranslations[key]) {
    return fullTranslations[key];
  }
  if (wordMap[enVal]) {
    return wordMap[enVal];
  }
  
  // Clean translation of common phrases
  let res = enVal;
  for (const [eng, hin] of Object.entries(wordMap)) {
    const p = new RegExp(`\\b${eng}\\b`, 'g');
    if (p.test(res)) {
      res = res.replace(p, hin);
    }
  }
  return res;
}

